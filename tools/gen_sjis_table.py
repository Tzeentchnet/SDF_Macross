#!/usr/bin/env python3
"""Generate port/src/sjis_table.odin: the CP932 (Shift-JIS) code page.

The game stores text as Microsoft's Shift-JIS variant (CP932). The port needs
both directions: decoding to export the game's strings as UTF-8 CSV, and
encoding a translator's UTF-8 CSV back to the bytes the game's font renders.
The table is derived from Python's own codec, so it contains only the public
character-set standard and no game data.

Run from the repository root:

    python tools\\gen_sjis_table.py --output port\\src\\sjis_table.odin

Without --output, the same LF-terminated ASCII bytes are written to stdout.
"""

from __future__ import annotations

import argparse
import io
import sys
from pathlib import Path


def double_byte_pairs() -> list[tuple[int, int]]:
    """(sjis, codepoint) for every decodable two-byte CP932 sequence."""
    pairs = []
    leads = list(range(0x81, 0xA0)) + list(range(0xE0, 0xFD))
    for lead in leads:
        for trail in range(0x40, 0xFD):
            if trail == 0x7F:
                continue
            raw = bytes((lead, trail))
            try:
                text = raw.decode("cp932")
            except UnicodeDecodeError:
                continue
            if len(text) != 1 or ord(text) > 0xFFFF:
                raise ValueError(f"CP932 sequence {raw.hex()} is not a BMP character")
            pairs.append(((lead << 8) | trail, ord(text)))
    return pairs


def encode_pairs() -> list[tuple[int, int]]:
    """Include the codec's preferred bytes and its non-round-tripping aliases."""
    pairs = []
    for cp in range(0x110000):
        try:
            raw = chr(cp).encode("cp932")
        except UnicodeEncodeError:
            continue
        if len(raw) == 1:
            continue
        if len(raw) != 2 or cp > 0xFFFF:
            raise ValueError(f"CP932 encoding of U+{cp:04X} does not fit the table")
        pairs.append((cp, int.from_bytes(raw, "big")))
    return pairs


def emit(name: str, values: list[int], out) -> None:
    out.write(f"{name} := [{len(values)}]u32{{\n")
    for start in range(0, len(values), 8):
        chunk = ", ".join(f"0x{v:08x}" for v in values[start : start + 8])
        out.write(f"\t{chunk},\n")
    out.write("}\n")


def generate() -> bytes:
    decode = sorted((sjis << 16) | cp for sjis, cp in double_byte_pairs())
    encode = sorted((cp << 16) | sjis for cp, sjis in encode_pairs())
    out = io.StringIO(newline="\n")
    out.write("// Generated by tools/gen_sjis_table.py from Python's cp932 codec. Do not edit.\n")
    out.write("// The public CP932 (Shift-JIS) character set; no game data.\n")
    out.write("package main\n\n")
    out.write("// Two-byte Shift-JIS to Unicode: (sjis << 16) | code point, sorted.\n")
    out.write("@(rodata)\n")
    emit("SJIS_DECODE", decode, out)
    out.write("\n")
    out.write("// Unicode to two-byte Shift-JIS: (code point << 16) | sjis, sorted.\n")
    out.write("@(rodata)\n")
    emit("SJIS_ENCODE", encode, out)
    return out.getvalue().encode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-o", "--output", type=Path, help="write the generated table directly to this file")
    args = parser.parse_args()
    try:
        data = generate()
        if args.output is None:
            sys.stdout.buffer.write(data)
        else:
            args.output.write_bytes(data)
    except (OSError, ValueError) as exc:
        print(f"{parser.prog}: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
